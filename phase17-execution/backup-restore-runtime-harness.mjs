import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
const db = process.env.DATABASE_URL;
if (!db) throw new Error('DATABASE_URL required');
const file = '/tmp/phase17-backup.dump';
const q = sql => execFileSync('psql',[db,'-v','ON_ERROR_STOP=1','-At','-c',sql],{encoding:'utf8'}).trim();
const run = (cmd,args) => execFileSync(cmd,args,{stdio:'pipe',encoding:'utf8'});
q('DROP TABLE IF EXISTS phase17_backup_probe');
q('CREATE TABLE phase17_backup_probe(id integer PRIMARY KEY, marker text NOT NULL)');
q("INSERT INTO phase17_backup_probe VALUES (1,'backup-drill-original'),(2,'backup-drill-secondary')");
const before = q('SELECT id||\':\'||marker FROM phase17_backup_probe ORDER BY id');
run('pg_dump',['--format=custom','--file',file,db]);
q('DROP TABLE phase17_backup_probe');
run('pg_restore',['--dbname',db,'--clean','--if-exists',file]);
const after = q('SELECT id||\':\'||marker FROM phase17_backup_probe ORDER BY id');
const status = before===after && after.includes('backup-drill-original') ? 'PASS' : 'FAIL';
const report={schemaVersion:'1.0.0',status,checks:{backupCreated:true,dataRestored:status==='PASS',roundTripExact:before===after},before,after,artifact:file};
writeFileSync('phase17-execution/backup-runtime.json',JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report,null,2));
if(status!=='PASS') process.exitCode=1;
